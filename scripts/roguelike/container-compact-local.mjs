  const response=page.waitForResponse(r=>r.request().method()==='PATCH'&&r.url().includes('/api/characters-v3/'));
  await button(direction,card).click();assert((await response).ok());
  await expect(page.getByRole('dialog',{name:'Переместить предметы'})).toHaveCount(0);
