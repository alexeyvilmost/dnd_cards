 await page.getByRole('navigation',{name:'Разделы листа'}).getByRole('button',{name:'Инвентарь',exact:true}).click();
 if(!await dialog.isVisible())await open();
 const size=await button('in',single).boundingBox();assert(size.width===56&&size.height===56);
 const badges=await dialog.locator('.container-item-quantity').evaluateAll(nodes=>nodes.map(n=>{const a=n.getBoundingClientRect(),b=n.parentElement.getBoundingClientRect();return a.right<=b.right&&a.bottom<=b.bottom&&a.top>b.top;}));assert(badges.every(Boolean));
